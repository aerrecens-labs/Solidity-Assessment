import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function readAbi(contractFile, contractName) {
  const artifactPath = path.join(
    root,
    "artifacts",
    "contracts",
    contractFile,
    `${contractName}.json`
  );
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  return artifact.abi;
}

export function exportAbis() {
  const treasuryVaultAbi = readAbi("TreasuryVault.sol", "TreasuryVault");
  const testTokenAbi = readAbi("TestToken.sol", "TestToken");
  const outPath = path.join(root, "src", "contracts", "abis.ts");

  const contents = `// Generated by scripts/export-abi.js. Do not edit by hand.
export const treasuryVaultAbi = ${JSON.stringify(treasuryVaultAbi, null, 2)} as const

export const testTokenAbi = ${JSON.stringify(testTokenAbi, null, 2)} as const
`;

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, contents);
  console.log("Wrote", path.relative(root, outPath));
}

const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  exportAbis();
}
